import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 960, height: 540 } });
const errs = [];
p.on('pageerror', (e) => errs.push('pageerror ' + e.message));
p.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ' ' + m.text().slice(0, 200)); });
await p.goto('http://localhost:4173/?q=low&fixed');
await p.waitForFunction(() => window.__neon && window.__neon.state() === 'title', null, { timeout: 600000 });
const N = (fn, ...a) => p.evaluate(([f, args]) => window.__neon[f](...args), [fn, a]);
const sim = async (s) => { const t0 = await N('simTime'); await p.waitForFunction((t) => window.__neon.simTime() >= t, t0 + s, { timeout: 600000, polling: 300 }); };
await N('start'); await sim(6);
console.log('free ride peds', JSON.stringify(await N('peds')));
console.log('wallCheck', JSON.stringify(await N('wallCheck')));
console.log('errNote', await p.evaluate(() => document.getElementById('err-note')?.textContent));
// story mission + restart through the real pause button
await N('story', 'm1'); await sim(4);
console.log('story', JSON.stringify(await N('storyState')));
await p.keyboard.press('Escape'); await sim(0.5).catch(() => {});
await p.waitForTimeout(500);
console.log('paused state', await N('state'), 'restart visible', await p.evaluate(() => { const b = document.querySelector('[data-act="m-restart"]'); return b ? getComputedStyle(b).display : 'missing'; }));
const t = await p.evaluate(() => { const b = document.querySelector('[data-act="m-restart"]'); const t0 = performance.now(); b.click(); return performance.now() - t0; });
console.log('restart click handler ms', t.toFixed(0));
await p.waitForTimeout(1500);
console.log('after restart', await N('state'), JSON.stringify(await N('storyState')));
await sim(3);
console.log('peds in story', (await N('peds')).length, 'errNote', await p.evaluate(() => document.getElementById('err-note')?.textContent));
console.log('errors', JSON.stringify(errs.slice(0, 10)));
await b.close();
